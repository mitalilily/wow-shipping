items=[]
for md in sorted((ROOT/'.agents/skills').glob('*/SKILL.md')):
    valid,message=validator.validate_skill(md.parent)
    if not valid: raise RuntimeError(f'{md}: {message}')
    meta=yaml.safe_load(re.match(r'^---\n(.*?)\n---',md.read_text(encoding='utf-8'),re.S).group(1))
    name=meta['name']
    assert discovered.get(name,{}).get('enabled'), f'Not discovered/enabled: {name}'
    item=provenance.get(name,{}).copy()
    if name in {'ui-ux-pro-max','slides'} or item.get('repo')=='nextlevelbuilder/ui-ux-pro-max-skill':
        item.update(repo='nextlevelbuilder/ui-ux-pro-max-skill',sha='npm:ui-ux-pro-max-cli@2.15.0',
                    inspected_sha=repo_map['nextlevelbuilder/ui-ux-pro-max-skill']['sha'],
                    path='generated by uipro init --ai codex --offline')
        if name=='slides': item['adaptations']=['Moved argument-hint into metadata']
    if name=='pixel-perfect-website-cloner':
        item.update(repo='local custom skill',sha='local',path='.agents/skills/pixel-perfect-website-cloner',adaptations=[])
    item.update(name=name,description=meta['description'],location=str(md.parent.relative_to(ROOT)).replace('\\','/'),
                status='Metadata validation and Codex discovery passed',invocation='$'+name,
                skill_sha256=hashlib.sha256(md.read_bytes()).hexdigest())
    items.append(item)
assert len(items)==len({x['name'] for x in items})
for name in ('ui-ux-pro-max','slides'):
    dest=ROOT/'.agents/skills'/name/'LICENSE'
    if not dest.exists(): shutil.copy2(Path(repo_map['nextlevelbuilder/ui-ux-pro-max-skill']['path'])/'LICENSE',dest)
