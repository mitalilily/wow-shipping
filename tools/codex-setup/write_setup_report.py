OUT = CACHE / 'validation'
repos = json.loads((CACHE/'repository-inspection.json').read_text(encoding='utf-8'))
provenance = {x['name']:x for x in json.loads((CACHE/'installed-skills.json').read_text(encoding='utf-8'))}
repo_map = {x['repo']:x for x in repos}
spec = importlib.util.spec_from_file_location('validator',Path.home()/'.codex/skills/.system/skill-creator/scripts/quick_validate.py')
