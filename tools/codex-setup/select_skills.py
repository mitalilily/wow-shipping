"""Audit upstream skill frontmatter and select requested website capabilities."""
import importlib.util
import json
import pathlib
import re
import yaml

ROOT = pathlib.Path(__file__).resolve().parents[2]
CACHE = ROOT / '.codex-tools'
CODEX = pathlib.Path.home() / '.codex'
spec = importlib.util.spec_from_file_location('validate', CODEX / 'skills/.system/skill-creator/scripts/quick_validate.py')
validator = importlib.util.module_from_spec(spec)
spec.loader.exec_module(validator)

CODEX_SKILLS = {
    'audit-reference-originality', 'browser-video-recording',
    'html-to-interaction-prompts', 'iterate-until-verified',
    'optimize-web-animations', 'performance-profiling',
    'stitched-full-page-capture', 'video-to-superprompt',
    'web-technique-to-skill',
}

def selected(repo, path):
    parts = pathlib.PurePosixPath(path).parts
    if repo in {'santowilem/skills', 'greensock/gsap-skills', 'cesartevisual/threejs-skills', 'Moh4696/open-3d-skills', 'ChromeDevTools/chrome-devtools-mcp'}:
        return parts[0] == 'skills'
    if repo == 'MengTo/Skills':
        return (parts[1] in {'web-design', 'ui', '3d'} or
                parts[1] == 'codex' and parts[2] in CODEX_SKILLS or
                parts[1] == 'media' and parts[2] == 'url-to-motion-design' or
                parts[1] == 'workflow' and parts[2] in {'workflow-progress-screenshots', 'workflow-score-to-target'})
    if repo == 'vercel-labs/agent-browser':
        return path == 'skills/agent-browser/SKILL.md'
    if repo == 'nextlevelbuilder/ui-ux-pro-max-skill':
        return parts[0:3] == ('cli', 'assets', 'skills') and parts[3] in {'banner-design', 'brand', 'design', 'design-system', 'ui-styling'}
    # UI/UX core is generated by its official CLI with scripts + datasets.
    return False

def main():
    result = []
    for repo in json.loads((CACHE / 'repository-inspection.json').read_text()):
        for path in repo.get('skills', []):
            if not selected(repo['repo'], path):
                continue
            src = pathlib.Path(repo['path']) / path
            content = src.read_text(encoding='utf-8-sig')
            front = re.match(r'^---\n(.*?)\n---', content, re.S)
            try:
                meta = yaml.safe_load(front.group(1)) if front else {}
            except Exception as exc:
                meta = {'error': str(exc)}
            name = meta.get('name', src.parent.name)
            installed_name = 'open3d-threejs-scene' if repo['repo'] == 'Moh4696/open-3d-skills' and name == 'threejs-scene' else name
            valid, message = validator.validate_skill(src.parent)
            item = {'repo': repo['repo'], 'sha': repo['sha'], 'path': path.rsplit('/', 1)[0],
                    'name': installed_name, 'upstream_name': name,
                    'description': meta.get('description', ''), 'upstream_valid': valid,
                    'validation': message, 'metadata_keys': list(meta)}
            result.append(item)
    names = [x['name'] for x in result]
    assert len(names) == len(set(names)), 'Duplicate skill names'
    (CACHE / 'selected-skills.json').write_text(json.dumps(result, indent=2), encoding='utf-8')
    from collections import Counter
    print('Selected:', dict(Counter(x['repo'] for x in result)))
    print('Total:', len(result))
    for item in result:
        if not item['upstream_valid']:
            print(item['name'], item['validation'])

if __name__ == '__main__':
    main()
